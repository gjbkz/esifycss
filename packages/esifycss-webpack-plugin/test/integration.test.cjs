const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const webpack = require('webpack');
const Plugin = require('../lib/cjs');
const {Session} = require('esifycss');

async function fixture(t, files) {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'esifycss-webpack-'));
    t.after(() => fs.rm(directory, {recursive: true, force: true}));
    for (const [name, code] of Object.entries(files)) await fs.writeFile(path.join(directory, name), code);
    return directory;
}
async function compile(t, directory, extra = {}) {
    const compiler = webpack({
        mode: 'production', context: directory, entry: './entry.js',
        output: {path: path.join(directory, 'output'), filename: 'bundle.js'},
        optimization: {minimize: false}, plugins: [new Plugin()], ...extra,
    });
    t.after(() => new Promise((resolve, reject) => compiler.close(error => error ? reject(error) : resolve())));
    const stats = await new Promise((resolve, reject) => compiler.run((error, stats) => error ? reject(error) : resolve(stats)));
    assert.equal(stats.hasErrors(), false, stats.toString({all: false, errors: true}));
    return fs.readFile(path.join(directory, 'output/bundle.js'), 'utf8');
}
function execute(code) {
    const rules = [];
    const style = {parentNode: null, sheet: {cssRules: rules, insertRule(rule, index) {rules.splice(index, 0, rule);}}};
    const context = {document: {createElement() {return style;}, head: {appendChild(node) {node.parentNode = this;}}}};
    vm.runInNewContext(code, context);
    return {result: context.result, rules};
}

test('CommonJS constructor and default/named exports are preserved', () => {
    assert.equal(Plugin, Plugin.default);
    assert.equal(Plugin, Plugin.EsifyCSSWebpackPlugin);
});

test('Webpack consumes modules generated by the local esifycss core', async t => {
    const directory = await fixture(t, {
        'style.module.css': '.button {color: red}',
        'entry.js': "import {className} from './style.module.css'; globalThis.result = className;",
    });
    await new Session({include: path.join(directory, 'style.module.css'), helper: path.join(directory, 'helper.js')}).start();
    const {result, rules} = execute(await compile(t, directory));
    assert.ok(rules.some(rule => rule.includes(`.${result.button}`) && rule.includes('color:red')));
});

for (const extension of ['js', 'ts']) {
    test(`resolves .module.css.${extension}`, async t => {
        const directory = await fixture(t, {
            [`style.module.css.${extension}`]: "export const className = {button: 'generated'};",
            'entry.js': "import {className} from './style.module.css'; globalThis.result = className;",
        });
        const {result} = execute(await compile(t, directory));
        assert.equal(result.button, 'generated');
    });
}

test('JavaScript takes precedence over TypeScript sidecars', async t => {
    const directory = await fixture(t, {
        'style.module.css.js': "export const className = {button: 'js'};",
        'style.module.css.ts': "export const className = {button: 'ts'};",
        'entry.js': "import {className} from './style.module.css'; globalThis.result = className;",
    });
    assert.equal(execute(await compile(t, directory)).result.button, 'js');
});

test('CSS without a generated sidecar falls through to Webpack', async t => {
    const directory = await fixture(t, {
        'style.module.css': '.button {color: red}',
        'entry.js': "import css from './style.module.css'; globalThis.result = css;",
    });
    const code = await compile(t, directory, {module: {rules: [{test: /\.css$/, type: 'asset/source'}]}});
    assert.equal(execute(code).result, '.button {color: red}');
});
